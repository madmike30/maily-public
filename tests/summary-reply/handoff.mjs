import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const path = 'services/Maily.OutlookAddin.Web/wwwroot/addin/js/summary-reply.js';
const window = {};
vm.runInNewContext(fs.readFileSync(path, 'utf8'), { window });
const api = window.MailySummaryReply;
assert.deepEqual(Array.from(api.actions('- Confirm the date.\n- Send the agenda.')), ['Confirm the date.', 'Send the agenda.'], 'String bullets from the real summary API must be individually selectable');
const original = { itemId: 'synthetic-one' };
let item = original, request, inserts = 0, opens = 0;
const snapshot = { request: { compose: { subject: 'Synthetic', bodyText: 'Thread' }, operation: { currentDraft: 'I cannot attend.', userInstruction: 'Rewrite my draft.' } }, composeState: { body: 'original', bodyType: 'html', userDraftText: 'I cannot attend.', canRewriteUserDraft: true } };
const office = { captureComposeContext: () => original, assertComposeContext: () => { if (item !== original) throw Error('changed'); }, getComposeSnapshot: async () => structuredClone(snapshot), callJson: async (url, options) => { request = JSON.parse(options.body); return { draft: { text: 'I cannot attend, thank you.' } }; }, insertGeneratedDraft: async (draft, options) => { assert.equal(options.expectedBody, 'original'); assert.equal(options.rewriteComposeBody, true); inserts++; } };
const flow = api.create({ office, getItem: () => item, surface: 'compose', defaults: {} });
flow.bind({ subject: 'Synthetic', bodyText: 'Thread' });
await flow.preview(['Confirm attendance']);
assert.equal(request.operation.currentDraft, 'I cannot attend.');
assert.match(request.operation.userInstruction, /draft.*authoritative/i);
assert.match(request.operation.userInstruction, /Confirm attendance/);
assert.equal(inserts, 0, 'Preview must never edit Outlook');
await flow.apply(); assert.equal(inserts, 1);
await assert.rejects(flow.apply(), /preview/i, 'Apply must consume preview');
flow.bind({ bodyText: 'Thread' }); item = { itemId: 'synthetic-two' };
await assert.rejects(flow.preview([]), /changed/i);
item = original; flow.bind({ bodyText: 'Thread' });
office.callJson = async () => { item = { itemId: 'synthetic-two' }; return { draft: { text: 'stale' } }; };
await assert.rejects(flow.preview([]), /changed/i);
item = original;
let sourceFontApplied = false;
original.body = { getAsync(type, callback) { assert.equal(type, 'html'); callback({ status: 'succeeded', value: '<p style="font-family:Arial;font-size:14pt">Synthetic original</p>' }); } };
const read = api.create({ office: { applyComposeTypography(html, editable, source) { assert.equal(editable, ''); assert.match(source, /Arial/); sourceFontApplied = true; return html; }, callJson: async (url, options) => { request = JSON.parse(options.body); return { draft: { text: '<unsafe> & safe' } }; } }, getItem: () => item, surface: 'read', defaults: {} });
original.displayReplyFormAsync = (html, callback) => { assert.match(html, /&lt;unsafe&gt; &amp; safe/); opens++; callback({ status: 'succeeded' }); };
read.bind({ subject: 'Synthetic', bodyText: 'Context', fromAddress: 'sender@example.invalid' });
await read.preview([]); assert.equal(opens, 0); assert.doesNotMatch(request.operation.userInstruction, /Selected topics/);
assert.deepEqual(request.compose.to, ['sender@example.invalid'], 'Recipients must use the API string-list contract');
await read.apply(); assert.equal(opens, 1); assert.equal(sourceFontApplied, true);
assert.deepEqual(Array.from(api.actions([])), []);
assert.deepEqual(Array.from(api.actions(['Send reply', '', 'Send reply'])), ['Send reply']);
console.log('PASS: summary reply preview, authoritative draft, selected actions, stale item, explicit apply, read HTML escaping, no duplicate apply');
