Equal(blocked.AfterConnectionGuide,SetupAction.Install,"Repaired preflight continues installation once");
Equal(flow.AfterConnectionGuide,SetupAction.CheckConnection,"Already installed payload is never replaced from the connection guide");
blocked.InstallationFinished(23,false);
Equal(blocked.NextAction,SetupAction.Close,"Unsupported registration must stop without remove/reinstall advice");
Console.WriteLine("PASS connection outcomes preserve the correct next action");
