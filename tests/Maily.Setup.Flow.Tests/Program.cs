using Maily.OutlookAddin.Setup;
static void Equal<T>(T actual,T expected,string message) { if(!EqualityComparer<T>.Default.Equals(actual,expected)) throw new Exception(message + $" expected={expected}; actual={actual}"); }
var flow = new SetupFlow();
flow.InstallationFinished(20, true);
Equal(flow.NextAction,SetupAction.Connect,"Installed application must resume connection, not repeat replacement");
Console.WriteLine("PASS installed application resumes connection");
flow.InstallationFinished(21, true);
Equal(flow.NextAction,SetupAction.CheckConnection,"Cache refresh resumes verification");
flow.ConnectionFinished(1);
Equal(flow.NextAction,SetupAction.CheckConnection,"Readiness failure must not reinstall");
flow.ConnectionFinished(0);
Equal(flow.NextAction,SetupAction.OpenOutlook,"Only verified connection offers Outlook");
Equal(flow.Message.Contains("quick tour") && flow.Message.Contains("style"),true,"Successful setup should suggest the optional style-learning tour");
var blocked = new SetupFlow();
blocked.InstallationFinished(20,false);
